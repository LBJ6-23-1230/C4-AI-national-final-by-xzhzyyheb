"""Prepare a development, independent demo or production HarmonyOS build."""
import argparse
import ipaddress
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "app/entry/src/main/ets/api/BuildEnvironment.ets"


def render(environment, api_url):
    url = urlsplit(api_url)
    if url.scheme not in {"http", "https"} or not url.hostname or url.username or url.password or url.query or url.fragment or url.path not in {"", "/"}:
        raise ValueError("API URL must be an origin without credentials, path, query or fragment")
    if any(char in api_url for char in "'\"\\\n\r"):
        raise ValueError("invalid URL characters")
    if environment == "production":
        if url.scheme != "https" or url.hostname == "localhost" or url.hostname.endswith((".local", ".example", ".example.com")):
            raise ValueError("production requires your real public HTTPS API domain")
        try:
            ipaddress.ip_address(url.hostname)
        except ValueError:
            if "." not in url.hostname:
                raise ValueError("production requires a public domain")
        else:
            raise ValueError("production requires a domain, not an IP address")
    debug = "false" if environment == "production" else "true"
    return ("/** Generated by tools/prepare_app_environment.py. Never put secrets here. */\n"
            "export class BuildEnvironment {\n"
            f"  static readonly NAME: string = '{environment}';\n"
            f"  static readonly API_URL: string = '{api_url.rstrip('/')}';\n"
            f"  static readonly ALLOW_DEBUG: boolean = {debug};\n"
            f"  static readonly ALLOW_DEMO: boolean = {debug};\n" + "}\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--environment", choices=["development", "demo", "production"], required=True)
    parser.add_argument("--api-url", required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render(args.environment, args.api_url)
    if args.check:
        if TARGET.read_text(encoding="utf-8") != expected:
            raise SystemExit("Build environment mismatch. Prepare the intended environment before packaging.")
    else:
        TARGET.write_text(expected, encoding="utf-8")
    print(f"App environment verified: {args.environment}")


if __name__ == "__main__":
    main()
