# -*- coding: utf-8 -*-
"""Build the Huawei service-account JSON and a Push Kit JWT.

Input:
  - the service-account JSON downloaded from AGC (it contains project_id,
    key_id, sub_account and an empty private_key field)
  - the local private key generated by tools/generate_push_keypair.py

Output:
  - private/huawei-push-service-account.json  (complete key file)
  - private/push.jwt                          (valid for 1 hour; manual testing only)

Usage:
    python tools/prepare_push_credentials.py <downloaded-private.json>
"""
from __future__ import annotations

import argparse
import base64
import json
import time
from pathlib import Path

from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import padding

OUT = Path(__file__).resolve().parents[1] / "private"
AUD = "https://oauth-login.cloud.huawei.com/oauth2/v3/token"


def _b64url(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode("ascii")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("service_account_json", help="JSON downloaded from AGC")
    parser.add_argument(
        "--private-key",
        default=str(OUT / "huawei-push-private.pem"),
        help="local RSA private key PEM",
    )
    parser.add_argument("--ttl", type=int, default=3600, help="JWT lifetime seconds")
    args = parser.parse_args()
    if not 1 <= args.ttl <= 3600:
        parser.error("--ttl must be between 1 and 3600 seconds")

    sa_path = Path(args.service_account_json)
    key_path = Path(args.private_key)
    if not sa_path.exists():
        print(f"[X] service account JSON not found: {sa_path}")
        return 1
    if not key_path.exists():
        print(f"[X] private key not found: {key_path}")
        return 1

    sa = json.loads(sa_path.read_text(encoding="utf-8-sig"))
    key_id = str(sa.get("key_id") or "").strip()
    sub_account = str(sa.get("sub_account") or "").strip()
    project_id = str(sa.get("project_id") or "").strip()
    if not key_id or not sub_account or not project_id:
        print("[X] JSON is missing project_id / key_id / sub_account")
        return 1

    private_pem = key_path.read_bytes()
    private_key = serialization.load_pem_private_key(private_pem, password=None)
    private_text = private_pem.decode("utf-8")

    sa["private_key"] = private_text
    OUT.mkdir(parents=True, exist_ok=True)
    full_path = OUT / "huawei-push-service-account.json"
    full_path.write_text(json.dumps(sa, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    iat = int(time.time())
    exp = iat + args.ttl
    header = {"kid": key_id, "typ": "JWT", "alg": "PS256"}
    payload = {"aud": AUD, "iss": sub_account, "iat": iat, "exp": exp}

    header_b64 = _b64url(json.dumps(header, separators=(",", ":")).encode("utf-8"))
    payload_b64 = _b64url(json.dumps(payload, separators=(",", ":")).encode("utf-8"))
    signing_input = f"{header_b64}.{payload_b64}".encode("ascii")
    signature = private_key.sign(
        signing_input,
        padding.PSS(mgf=padding.MGF1(hashes.SHA256()), salt_length=padding.PSS.DIGEST_LENGTH),
        hashes.SHA256(),
    )
    token = f"{header_b64}.{payload_b64}.{_b64url(signature)}"

    jwt_path = OUT / "push.jwt"
    jwt_path.write_text(token + "\n", encoding="ascii")

    print("=" * 72)
    print("Service account prepared")
    print(f"Full key file  : {full_path}")
    print(f"JWT file       : {jwt_path}")
    print(f"JWT issued at  : {time.strftime('%Y-%m-%d %H:%M:%S', time.localtime(iat))}")
    print(f"JWT expires at : {time.strftime('%Y-%m-%d %H:%M:%S', time.localtime(exp))}")
    print(f"JWT length     : {len(token)}")
    print("=" * 72)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
